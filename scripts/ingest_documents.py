def create_samples(dir_path: Path) -> None:
    dir_path.mkdir(parents=True, exist_ok=True)
    for name, content in SAMPLE_DOCS.items():
        (dir_path / name).write_text(content, encoding="utf-8")
        print(f"生成示例文档: {dir_path / name}")


def main() -> None:
    parser = argparse.ArgumentParser(description="知识库文档批量入库")
    parser.add_argument("--dir", default="data/documents", help="文档目录")
    parser.add_argument("--doc-type", default="standard",
                        choices=["standard", "manual", "case", "spec"], help="文档类型")
    parser.add_argument("--create-samples", action="store_true", help="生成示例知识文档")
    args = parser.parse_args()

    root = Path(args.dir)
    if args.create_samples:
        create_samples(root)

    files = [p for p in sorted(root.rglob("*"))
             if p.is_file() and p.suffix.lower() in {".txt", ".md", ".pdf", ".docx"}]
    if not files:
        print(f"目录 {root} 下无待入库文档。可使用 --create-samples 生成示例文档。")
        return

    ensure_extensions()
    ingestor = KnowledgeIngestor()
    total = 0
    with SessionLocal() as db:
        for f in files:
            try:
                n = ingestor.ingest_file(db, f, doc_type=args.doc_type)
                total += n
                print(f"✅ {f.name}: {n} 块")
            except Exception as e:
                print(f"❌ {f.name}: {e}")
    print(f"完成，共入库 {total} 个文本块。")


if __name__ == "__main__":
    main()
